import crypto from "node:crypto";
import fs from "node:fs/promises";
import path from "node:path";

// When run from `web/`, repo root is one directory up.
const REPO_ROOT = path.resolve(process.cwd(), "..");
const REFRESH_VIZIER =
  process.argv.includes("--refresh-vizier") || process.env.REFRESH_VIZIER === "1";

function parseCsvLine(line) {
  const out = [];
  let current = "";
  let inQuotes = false;

  for (let index = 0; index < line.length; index += 1) {
    const character = line[index];

    if (inQuotes) {
      if (character === '"') {
        if (line[index + 1] === '"') {
          current += '"';
          index += 1;
        } else {
          inQuotes = false;
        }
      } else {
        current += character;
      }
      continue;
    }

    if (character === ",") {
      out.push(current);
      current = "";
    } else if (character === '"') {
      inQuotes = true;
    } else {
      current += character;
    }
  }

  out.push(current);
  return out;
}

async function readCsv(filePath) {
  const text = await fs.readFile(filePath, "utf8");
  const lines = text.split(/\r?\n/).filter((line) => line.length > 0);
  if (lines.length === 0) throw new Error(`Empty CSV: ${filePath}`);

  const columns = parseCsvLine(lines[0]);
  const rows = lines.slice(1).map((line) => {
    const values = parseCsvLine(line);
    return Object.fromEntries(columns.map((column, index) => [column, values[index] ?? ""]));
  });
  return { columns, rows };
}

function humanizeSlug(slug) {
  const preserveUpper = new Set(["mw", "m31"]);
  const keepLower = new Set(["gc"]);
  return String(slug)
    .split(/[_-]+/)
    .filter(Boolean)
    .map((word) => word.toLowerCase())
    .map((word) => {
      if (preserveUpper.has(word)) return word.toUpperCase();
      if (keepLower.has(word)) return word;
      return word.length ? word[0].toUpperCase() + word.slice(1) : word;
    })
    .join(" ");
}

function sha256(text) {
  return crypto.createHash("sha256").update(text).digest("hex");
}

async function writeDatasets() {
  const excludeFiles = new Set(["j_factor.csv", "pm_overview.csv"]);
  const titleBySlug = {
    dwarf_mw: "Dwarf galaxies (Milky Way)",
    dwarf_all: "Dwarf galaxies (All)",
    dwarf_m31: "Dwarf galaxies (M31)",
    dwarf_local_field: "Dwarf galaxies (Local field)",
    dwarf_local_field_distant: "Dwarf galaxies (Local field, distant)",
    gc_harris: "Globular clusters (Harris)",
    gc_dwarf_hosted: "Globular clusters (Dwarf-hosted)",
    gc_mw_new: "Globular clusters (Milky Way, new)",
    gc_ambiguous: "Globular clusters (Ambiguous)",
    gc_other: "Globular clusters (Other)",
  };

  const dataDir = path.resolve(REPO_ROOT, "data");
  const generatedDir = path.resolve(process.cwd(), "src", "generated");
  const publicDataDir = path.resolve(process.cwd(), "public", "data", "datasets");
  await Promise.all([
    fs.mkdir(generatedDir, { recursive: true }),
    fs.mkdir(publicDataDir, { recursive: true }),
  ]);

  const files = (await fs.readdir(dataDir))
    .filter((file) => file.endsWith(".csv") && !excludeFiles.has(file))
    .sort((left, right) => left.localeCompare(right));

  const summaries = [];
  const allRows = [];
  const expectedJsonFiles = new Set();
  for (const file of files) {
    const slug = path.basename(file, ".csv");
    const title = titleBySlug[slug] ?? humanizeSlug(slug);
    const { columns, rows } = await readCsv(path.resolve(dataDir, file));
    const payload = {
      schemaVersion: 1,
      slug,
      title,
      columns,
      totalRows: rows.length,
      rows,
    };
    const serialized = `${JSON.stringify(payload)}\n`;
    const outputName = `${slug}.json`;
    await fs.writeFile(path.resolve(publicDataDir, outputName), serialized, "utf8");
    expectedJsonFiles.add(outputName);
    allRows.push(...rows);
    summaries.push({
      slug,
      title,
      columns,
      totalRows: rows.length,
      dataPath: `/data/datasets/${outputName}`,
      bytes: Buffer.byteLength(serialized),
      sha256: sha256(serialized),
    });
  }

  for (const existing of await fs.readdir(publicDataDir)) {
    if (existing.endsWith(".json") && !expectedJsonFiles.has(existing)) {
      await fs.unlink(path.resolve(publicDataDir, existing));
    }
  }

  const summaryLines = [
    "// THIS FILE IS AUTO-GENERATED. DO NOT EDIT BY HAND.",
    "// Generated by scripts/generate-datasets.mjs",
    "",
    "export type DatasetRow = Record<string, string>;",
    "export type DatasetSummary = { slug: string; title: string; columns: string[]; totalRows: number; dataPath: string; bytes: number; sha256: string };",
    "export type DatasetPayload = { schemaVersion: number; slug: string; title: string; columns: string[]; totalRows: number; rows: DatasetRow[] };",
    "",
    `export const datasets: DatasetSummary[] = ${JSON.stringify(summaries, null, 2)};`,
    "",
    "export const datasetBySlug = Object.fromEntries(datasets.map((dataset) => [dataset.slug, dataset])) as Record<string, DatasetSummary>;",
    "",
  ];
  const summaryPath = path.resolve(generatedDir, "datasets_summary.ts");
  await fs.writeFile(summaryPath, `${summaryLines.join("\n")}\n`, "utf8");
  console.log(
    `Generated ${summaries.length} dataset JSON files and ${path.relative(process.cwd(), summaryPath)}`,
  );
  return allRows;
}

async function processWithConcurrency(items, limit, operation) {
  const results = [];
  let nextIndex = 0;
  const workers = new Array(Math.min(limit, items.length)).fill(0).map(async () => {
    while (nextIndex < items.length) {
      const index = nextIndex;
      nextIndex += 1;
      try {
        results[index] = await operation(items[index]);
      } catch (error) {
        results[index] = { error: String(error) };
      }
    }
  });
  await Promise.all(workers);
  return results;
}

async function fetchVizierForBibcode(bibcode) {
  const result = { catalogs: [], fetchedAt: new Date().toISOString() };
  try {
    const url = `https://vizier.u-strasbg.fr/viz-bin/asu-tsv?-ref=${encodeURIComponent(bibcode)}&-out.max=200`;
    const response = await fetch(url);
    if (!response.ok) {
      result.error = `vizier: ${response.status} ${(await response.text()).slice(0, 200)}`;
      return result;
    }
    const text = await response.text();
    const matches = Array.from(text.matchAll(/(?:\?|&)-source=([^&\s'"]+)/g));
    let catalogs = Array.from(
      new Set(matches.map((match) => decodeURIComponent(match[1]))),
    ).filter(Boolean);

    if (catalogs.length === 0) {
      const match = String(bibcode).match(/^(?:\d{4})([A-Za-z]{1,6})\.+(\d+)\.+(\d+)/);
      if (match) {
        const guess = `J/${match[1]}/${match[2]}/${match[3]}`;
        try {
          const fallback = await fetch(
            `https://vizier.u-strasbg.fr/viz-bin/asu-tsv?-source=${encodeURIComponent(guess)}&-out.max=200`,
          );
          if (fallback.ok) {
            const fallbackText = await fallback.text();
            catalogs = Array.from(
              new Set(
                Array.from(fallbackText.matchAll(/#Name:\s*([^\n\r]+)/g))
                  .map((item) => item[1].trim())
                  .filter((name) => name.startsWith(guess)),
              ),
            );
          }
        } catch {
          // The primary response remains useful even if the heuristic probe fails.
        }
      }
    }
    result.catalogs = catalogs;
  } catch (error) {
    result.error = String(error);
  }
  return result;
}

async function updateVizierCache(allRows) {
  const generatedDir = path.resolve(process.cwd(), "src", "generated");
  const cacheJsonPath = path.resolve(generatedDir, "vizier_catalogs.json");
  const cacheTsPath = path.resolve(generatedDir, "vizier_catalogs.ts");

  let cache = {};
  try {
    cache = JSON.parse(await fs.readFile(cacheJsonPath, "utf8"));
  } catch {
    console.warn("No existing VizieR cache found; starting with an empty cache.");
  }

  const found = new Set();
  const bibcodePattern = /(\d{4}[A-Za-z]{1,6}\.+\d+\.+\d+\w?)/g;
  for (const match of JSON.stringify(allRows).matchAll(bibcodePattern)) found.add(match[1]);
  const missing = Array.from(found)
    .sort()
    .filter((bibcode) => !(bibcode in cache));

  if (REFRESH_VIZIER && missing.length > 0) {
    console.log(`Refreshing ${missing.length} missing VizieR entries.`);
    const results = await processWithConcurrency(missing, 4, fetchVizierForBibcode);
    missing.forEach((bibcode, index) => {
      cache[bibcode] =
        results[index] ?? {
          catalogs: [],
          fetchedAt: new Date().toISOString(),
          error: "unknown",
        };
    });
  } else if (missing.length > 0) {
    console.log(
      `${missing.length} VizieR entries are not cached; normal generation stays offline. Run npm run refresh:vizier to fetch them.`,
    );
  }

  await fs.writeFile(cacheJsonPath, `${JSON.stringify(cache, null, 2)}\n`, "utf8");
  const wrapper = [
    "// THIS FILE IS AUTO-GENERATED. DO NOT EDIT BY HAND.",
    "// Generated by scripts/generate-datasets.mjs",
    "",
    `export const vizierCatalogs = ${JSON.stringify(cache, null, 2)} as const;`,
  ];
  await fs.writeFile(cacheTsPath, `${wrapper.join("\n")}\n`, "utf8");
}

async function main() {
  const allRows = await writeDatasets();
  await updateVizierCache(allRows);
}

main().catch((error) => {
  console.error(error);
  process.exitCode = 1;
});
