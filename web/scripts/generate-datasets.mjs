import fs from "node:fs/promises";
import path from "node:path";

// When run from `web/`, repo root is one directory up.
const REPO_ROOT = path.resolve(process.cwd(), "..");

function parseCsvLine(line) {
  const out = [];
  let cur = "";
  let inQuotes = false;

  for (let i = 0; i < line.length; i += 1) {
    const ch = line[i];

    if (inQuotes) {
      if (ch === '"') {
        const next = line[i + 1];
        if (next === '"') {
          cur += '"';
          i += 1;
        } else {
          inQuotes = false;
        }
      } else {
        cur += ch;
      }
      continue;
    }

    if (ch === ',') {
      out.push(cur);
      cur = "";
      continue;
    }

    if (ch === '"') {
      inQuotes = true;
      continue;
    }

    cur += ch;
  }

  out.push(cur);
  return out;
}

async function readCsv({ filePath, limitRows }) {
  const text = await fs.readFile(filePath, "utf8");
  const lines = text.split(/\r?\n/).filter((l) => l.length > 0);
  if (lines.length === 0) {
    throw new Error(`Empty CSV: ${filePath}`);
  }

  const header = parseCsvLine(lines[0]);
  const rows = [];

  for (let i = 1; i < lines.length; i += 1) {
    const values = parseCsvLine(lines[i]);
    const row = {};
    for (let c = 0; c < header.length; c += 1) {
      row[header[c]] = values[c] ?? "";
    }
    rows.push(row);
  }

  return { header, rows, totalLines: lines.length - 1 };
}

function humanizeSlug(slug) {
  const words = String(slug)
    .split(/[_\-]+/)
    .filter(Boolean)
    .map((w) => w.toLowerCase());

  const preserveUpper = new Set(["mw", "m31"]);
  const keepLower = new Set(["gc"]);

  return words
    .map((w) => {
      if (preserveUpper.has(w)) return w.toUpperCase();
      if (keepLower.has(w)) return w;
      return w.length ? w[0].toUpperCase() + w.slice(1) : w;
    })
    .join(" ");
}

async function main() {
  const excludeFiles = new Set(["j_factor.csv", "pm_overview.csv"]);

  const titleBySlug = {
    dwarf_mw: "Dwarf galaxies (Milky Way)",
    dwarf_all: "Dwarf galaxies (All)",
    dwarf_m31: "Dwarf galaxies (M31)",
    dwarf_local_field: "Dwarf galaxies (Local field)",
    dwarf_local_field_distant: "Dwarf galaxies (Local field, distant)",
    gc_harris: "Globular clusters (Harris)",
    gc_dwarf_hosted: "Globular clusters (Dwarf-hosted)",
    gc_mw_new: "Globular clusters (Milky Way, new)",
    gc_ambiguous: "Globular clusters (Ambiguous)",
    gc_other: "Globular clusters (Other)",
  };

  const dataDir = path.resolve(REPO_ROOT, "data");
  const files = (await fs.readdir(dataDir)).filter((f) => f.endsWith(".csv"));

  const datasets = files
    .filter((f) => !excludeFiles.has(f))
    .sort((a, b) => a.localeCompare(b))
    .map((file) => {
      const slug = path.basename(file, ".csv");
      return {
        slug,
        title: titleBySlug[slug] ?? humanizeSlug(slug),
        file,
      };
    });

  const generatedDir = path.resolve(process.cwd(), "src", "generated");
  await fs.mkdir(generatedDir, { recursive: true });

  const pieces = [];
  pieces.push("// THIS FILE IS AUTO-GENERATED. DO NOT EDIT BY HAND.");
  pieces.push("// Generated by scripts/generate-datasets.mjs");
  pieces.push("\nexport type DatasetRow = Record<string, string>;\n");
  pieces.push(
    "export type Dataset = { slug: string; title: string; columns: string[]; rows: DatasetRow[]; totalRows: number };\n",
  );

  pieces.push("export const datasets: Dataset[] = [");

  for (const ds of datasets) {
    const csvPath = path.resolve(REPO_ROOT, "data", ds.file);
    const { header, rows, totalLines } = await readCsv({ filePath: csvPath });

    // Preserve the CSV header order and include all columns.
    const columns = header;
    const orderedRows = rows;

    pieces.push("  {");
    pieces.push(`    slug: ${JSON.stringify(ds.slug)},`);
    pieces.push(`    title: ${JSON.stringify(ds.title)},`);
    pieces.push(`    columns: ${JSON.stringify(columns)},`);
    pieces.push(`    rows: ${JSON.stringify(orderedRows)},`);
    pieces.push(`    totalRows: ${JSON.stringify(totalLines)},`);
    pieces.push("  },");
  }

  pieces.push("] as const;\n\nexport const datasetBySlug = Object.fromEntries(datasets.map((d) => [d.slug, d])) as Record<string, Dataset>;\n",
  );

  const outPath = path.resolve(generatedDir, "datasets.ts");
  await fs.writeFile(outPath, pieces.join("\n"), "utf8");
  console.log(`Generated: ${path.relative(process.cwd(), outPath)}`);
}

main().catch((err) => {
  console.error(err);
  process.exitCode = 1;
});
