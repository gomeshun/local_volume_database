def sources_by_name() -> dict[str, KinematicSource]:
    """Return registered kinematics sources indexed by name.

    Returns
    -------
    dict[str, KinematicSource]
        Registry entries keyed by source name.
    """
    return {source.name: source for source in KINEMATIC_SOURCES}


def sources_by_bibcode() -> dict[str, list[KinematicSource]]:
    """Return registered kinematics sources indexed by ADS bibcode.

    Returns
    -------
    dict[str, list[KinematicSource]]
        Registry entries grouped by source-paper bibcode.
    """
    by_bibcode: dict[str, list[KinematicSource]] = {}
    for source in KINEMATIC_SOURCES:
        by_bibcode.setdefault(source.bibcode, []).append(source)
    return by_bibcode
